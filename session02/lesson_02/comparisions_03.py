#som comparisions == er lik
# != er ulik
# > og < er større enn og mindre enn
# >= og <= er større eller lik og mindre enn eller lik

age = int(input('Tap in your age here: '))
max_age = 63
min_age = 25

print (f'{age}' != max_age)
print (f'{age}' == max_age)
print (age  < min_age)
print (age >= min_age)
print (age <= min_age)

print (f'{age}' != min_age)
print (f'{age}' == min_age)
print (age > max_age)
print (age <= max_age)
print (age >= max_age)

